C.append(md(
"---\n",
"## Chương 3 – Mục 3.4: Mô hình ngôn ngữ (N-gram LM)\n\n",
"> **Tài liệu:** Huang et al. Ch.11; Jurafsky & Martin Ch.3\n\n",
"$$P_{MLE}(w_n|w_1..w_{n-1}) = \\frac{C(w_1..w_n)}{C(w_1..w_{n-1})}$$\n\n",
"| Phương pháp | Công thức | Đặc điểm |\n",
"|------------|----------|----------|\n",
"| **MLE** | C(ngram)/C(ctx) | Zero-prob với OOV |\n",
"| **Laplace (Add-1)** | (C+1)/(C_ctx+V) | Smooth nhưng redistribute nhiều |\n",
"| **Backoff** | MLE nếu có; hạ bậc×0.4 nếu không | Cân bằng tốt nhất |\n",
))

