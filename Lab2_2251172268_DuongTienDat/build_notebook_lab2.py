# ═══════════════════════════════════════════════════════════
C.append(md(
"---\n",
"## Chương 3 – Mục 3.1 + 3.3: Nhận dạng bằng HMM Gaussian\n\n",
"> **Tài liệu:** Huang et al. Ch.8 (HMM), Ch.9 (Acoustic Modeling); Rabiner & Schafer Ch.14\n\n",
"$$\\lambda = (A, B, \\pi) \\quad B(o|j) = \\mathcal{N}(o;\\mu_j,\\Sigma_j)$$\n\n",
"| Thuật toán | Mô tả |\n",
"|-----------|-------|\n",
"| **Forward** | Tính P(O\\|λ) theo quy nạp tiến |\n",
"| **Viterbi** | Tìm chuỗi trạng thái tối ưu q\\* |\n",
"| **Baum-Welch** | EM: ước lượng A, μ, σ² từ dữ liệu |\n",
))

C.append(code(
"# ── Định nghĩa HMM Gaussian (left-to-right) ──\n",
"import math\n",
"\n",
"class GaussianHMM:\n",
"    '''\n",
"    Whole-word HMM với Gaussian diagonal covariance.\n",
"    λ = (A, B, π):\n",
"      A[i,j]: P(qₜ=j | qₜ₋₁=i)  – ma trận chuyển trạng thái\n",
"      B(o|j): N(o; μⱼ, σ²ⱼ)    – phân phối phát sinh quan sát\n",
"      π[i]  : P(q₁=i)            – xác suất ban đầu\n",
"    '''\n",
"    def __init__(self, n_states=5, n_dim=13, label=''):\n",
"        self.n_states=n_states; self.n_dim=n_dim; self.label=label\n",
"        # Left-to-right: self-loop + forward\n",
"        self.A=np.zeros((n_states,n_states))\n",
"        for i in range(n_states):\n",
"            if i<n_states-1: self.A[i,i]=0.6; self.A[i,i+1]=0.4\n",
"            else: self.A[i,i]=1.0\n",
"        self.pi=np.zeros(n_states); self.pi[0]=1.0\n",
"        self.means=np.zeros((n_states,n_dim))\n",
"        self.vars =np.ones( (n_states,n_dim))\n",
"        self._lnc=-0.5*n_dim*np.log(2*np.pi)\n",
"\n",
"    def _log_b(self, obs):\n",
"        'log B(o|j) = log N(o; μⱼ, σ²ⱼ) cho tất cả j'\n",
"        single=obs.ndim==1\n",
"        if single: obs=obs[np.newaxis,:]\n",
"        T=obs.shape[0]; lb=np.zeros((T,self.n_states))\n",
"        for j in range(self.n_states):\n",
"            d=obs-self.means[j]\n",
"            lb[:,j]=self._lnc-0.5*np.sum(d**2/self.vars[j]+np.log(self.vars[j]),axis=1)\n",
"        return lb[0] if single else lb\n",
"\n",
"    def forward(self, obs):\n",
"        '''\n",
"        Thuật toán Forward (scaled):\n",
"          α₁(j) = πⱼ·B(o₁|j)\n",
"          αₜ(j) = [Σᵢ αₜ₋₁(i)·A[i,j]]·B(oₜ|j)\n",
"          P(O|λ) = Σⱼ αT(j)\n",
"        '''\n",
"        T=len(obs); lb=self._log_b(obs)\n",
"        alpha=np.zeros((T,self.n_states)); scales=np.zeros(T)\n",
"        alpha[0]=self.pi*np.exp(lb[0])\n",
"        scales[0]=alpha[0].sum()+1e-300; alpha[0]/=scales[0]\n",
"        for t in range(1,T):\n",
"            alpha[t]=(alpha[t-1]@self.A)*np.exp(lb[t])\n",
"            scales[t]=alpha[t].sum()+1e-300; alpha[t]/=scales[t]\n",
"        return np.sum(np.log(scales+1e-300)),alpha,scales\n",
"\n",
"    def viterbi(self, obs):\n",
"        '''\n",
"        Viterbi decoding:\n",
"          δₜ(j) = max_{q1..qt-1} P(O₁..Oₜ, qₜ=j|λ)\n",
"          δₜ(j) = maxᵢ[δₜ₋₁(i)·A[i,j]]·B(oₜ|j)\n",
"        Backtrack từ T→1 để tìm q*.\n",
"        '''\n",
"        T=len(obs); lb=self._log_b(obs)\n",
"        lA=np.log(self.A+1e-300); lpi=np.log(self.pi+1e-300)\n",
"        delta=np.full((T,self.n_states),-np.inf)\n",
"        psi  =np.zeros((T,self.n_states),dtype=int)\n",
"        delta[0]=lpi+lb[0]\n",
"        for t in range(1,T):\n",
"            for j in range(self.n_states):\n",
"                sc=delta[t-1]+lA[:,j]; bi=int(np.argmax(sc))\n",
"                delta[t,j]=sc[bi]+lb[t,j]; psi[t,j]=bi\n",
"        path=[0]*T; path[T-1]=int(np.argmax(delta[T-1]))\n",
"        for t in range(T-2,-1,-1): path[t]=psi[t+1,path[t+1]]\n",
"        return path,float(np.max(delta[T-1])),delta\n",
"\n",
"    def _backward(self, obs, scales):\n",
"        'Thuật toán Backward (scaled) – tính β'\n",
"        T=len(obs); lb=self._log_b(obs)\n",
"        beta=np.zeros((T,self.n_states)); beta[T-1]=1./(scales[T-1]+1e-300)\n",
"        for t in range(T-2,-1,-1):\n",
"            beta[t]=(self.A*np.exp(lb[t+1])*beta[t+1]).sum(axis=1)/(scales[t]+1e-300)\n",
"        return beta\n",
"\n",
"    def fit(self, obs_list, n_iter=20, tol=1e-4):\n",
"        '''\n",
"        Baum-Welch (EM):\n",
"          E-step: γₜ(j)=P(qₜ=j|O,λ), ξₜ(i,j)=P(qₜ=i,qₜ₊₁=j|O,λ)\n",
"          M-step: cập nhật A, μⱼ, σ²ⱼ\n",
"        '''\n",
"        all_obs=np.concatenate(obs_list,axis=0)\n",
"        idx=np.linspace(0,len(all_obs)-1,self.n_states,dtype=int)\n",
"        self.means=all_obs[idx].copy()\n",
"        self.vars =np.full_like(self.means,np.var(all_obs,axis=0).mean()+1e-6)\n",
"        lls=[]\n",
"        for it in range(n_iter):\n",
"            Anum=np.zeros_like(self.A); Aden=np.zeros(self.n_states)\n",
"            pi_acc=np.zeros(self.n_states)\n",
"            mnum=np.zeros_like(self.means); vnum=np.zeros_like(self.vars)\n",
"            gsum=np.zeros(self.n_states); tll=0.\n",
"            for obs in obs_list:\n",
"                T=len(obs); lb=self._log_b(obs)\n",
"                lp,alpha,scales=self.forward(obs)\n",
"                beta=self._backward(obs,scales); tll+=lp\n",
"                gm=alpha*beta; gs=gm.sum(axis=1,keepdims=True)\n",
"                gm/=np.where(gs==0,1e-300,gs)\n",
"                for t in range(T-1):\n",
"                    xi=alpha[t,:,None]*self.A*np.exp(lb[t+1])*beta[t+1]\n",
"                    xn=xi.sum()+1e-300; Anum+=xi/xn; Aden+=gm[t]\n",
"                pi_acc+=gm[0]\n",
"                for j in range(self.n_states):\n",
"                    wj=gm[:,j]\n",
"                    mnum[j]+=(wj[:,None]*obs).sum(axis=0)\n",
"                    vnum[j]+=(wj[:,None]*(obs-self.means[j])**2).sum(axis=0)\n",
"                    gsum[j]+=wj.sum()\n",
"            for i in range(self.n_states):\n",
"                d=Aden[i]+1e-300; self.A[i]=Anum[i]/d\n",
"                self.A[i]/=(self.A[i].sum()+1e-300)\n",
"            self.pi=pi_acc/(pi_acc.sum()+1e-300)\n",
"            for j in range(self.n_states):\n",
"                g=gsum[j]+1e-300\n",
"                self.means[j]=mnum[j]/g; self.vars[j]=np.maximum(vnum[j]/g,1e-6)\n",
"            lls.append(tll)\n",
"            if it>0 and abs(lls[-1]-lls[-2])<tol: break\n",
"        return lls\n",
"\n",
"    def score(self, obs):\n",
"        lp,_,_=self.forward(obs); return lp\n",
"\n",
"print('✓ GaussianHMM class OK')\n",
))

